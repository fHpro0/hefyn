import { readFileSync } from 'node:fs';
import { headlessSnippet, helperAllowSeeds, mcpServerSeeds, supportsMcp } from './manifest-profile.ts';
import { type AgentProfile, type AssistantConfig, type Seed, skillSeeds, versionDir } from './profiles.ts';

// What a session puts into its agent's config in the sandbox besides the model routing: the Assistant's instructions, skills (and a generated skill per helper),
// the MCP servers (as addresses on the model bridge: hefyn forwards them with the credentials, mcp-proxy.ts) and the permission to run the helper scripts.
// Pure: the database side (which skills and servers a chat gets) is session-items.ts. Skills and instructions are too big for the launch environment, so they go
// through `stdin` (written before the agent starts); MCP and helper setup are small and go with the launch seed (`launch`), after the manifest's own files.

/** "What to use where": for `role` (review, tests, ...) the base agent hands the work to `agent`, run headless in the same sandbox and folder. */
export interface Helper { role: string; agent: string; provider?: string | null; model?: string | null; /** may change files without asking; default: read-only */ edit?: boolean }
export interface ResolvedHelper { role: string; slug: string; profile: AgentProfile; version: string; provider: string | null; model: string | null; edit: boolean }

/** The bridge address a helper CLI uses: the path prefix tells the bridge which agent's key policy applies to its requests (host.ts modelFront strips it and checks the Assistant declares that helper). */
export const helperBase = (base: string, agentId: string) => `${base}/a/${agentId}`;

export const HELPER_DIR = '/tmp/.hefyn/helpers';
export const roleSlug = (role: string) => role.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '').slice(0, 32);
export const helperScript = (slug: string) => `${HELPER_DIR}/${slug}.sh`;
const sq = (v: string) => `'${v.replace(/'/g, `'\\''`)}'`;

/** The wrapper a base agent runs: the helper's own environment (key routing through the gateway, its config dir), then its headless command with the task as "$@". */
export function helperScriptText(h: ResolvedHelper, base: string): string {
  const dir = versionDir(h.profile.registryId, h.version), cmd = headlessSnippet(h.profile.spec, dir, h.edit);
  if (!cmd) throw new Error(`${h.profile.name} cannot be used as a helper`);
  const env = Object.entries(h.profile.env(dir, helperBase(base, h.profile.registryId))).map(([k, v]) => `export ${k}=${sq(v)}`);
  return ['#!/bin/sh', '# written by hefyn; the task is the one argument', ...env, cmd, ''].join('\n');
}

/** The skill that tells the base agent to hand `role` to the helper. */
export function helperSkill(h: ResolvedHelper, via: string): { name: string; files: Record<string, string> } {
  const name = `hefyn-helper-${h.slug}`, desc = `For ${h.role}, hand the work to ${h.profile.name}.`;
  return { name, files: { 'SKILL.md': `---\nname: ${name}\ndescription: ${JSON.stringify(desc)}\n---\nWhen the work is ${h.role}, do not do it yourself: hand it to ${h.profile.name}, another coding agent in this sandbox. It runs here, in the same folder, and knows nothing of this conversation, so write the whole task: what to do, which files, what a good result is.\n\nRun:\n\n    sh ${via} "<the task>"\n\nRead what it prints and check the changes it made, then tell the user the result.\n` } };
}

/** Built in, for every agent: how to write the chat's interactive UI (generated by `bun run openui:skill`). */
export const OPENUI_SKILL = { name: 'openui', files: { 'SKILL.md': readFileSync(new URL('./openui-skill.md', import.meta.url), 'utf8') } };

export interface SessionInput {
  profile: AgentProfile;
  /** the bridge address inside the sandbox (http://127.0.0.1:47000) */
  base: string;
  /** undefined: a chat without an Assistant (the instructions file is left alone) */
  instructions?: string;
  skills: AssistantConfig['skills'];
  helpers: ResolvedHelper[];
  /** MCP servers: `name` is how the agent knows it, `path` the proxy path on the bridge (/mcp/<id>) */
  mcp: { name: string; path: string }[];
}
export interface SessionPlan { stdin: Seed[]; launch: Seed[]; /** why something was left out (shown nowhere yet; tests read it) */ notes: string[] }

export function planSession(o: SessionInput): SessionPlan {
  const { profile, base } = o, notes: string[] = [];
  const helpers = o.helpers.filter((h) => { if (headlessSnippet(h.profile.spec, '', h.edit)) return true; notes.push(`${h.profile.name} cannot run headless${h.edit ? '' : ' read-only'}: helper "${h.role}" skipped`); return false; });
  const skills = [...o.skills, OPENUI_SKILL, ...helpers.map((h) => helperSkill(h, helperScript(h.slug)))];
  const stdin: Seed[] = [...(o.instructions === undefined ? [] : [{ path: `${profile.configDir}/${profile.instructionsFile}`, text: o.instructions }]), ...skillSeeds(profile, skills)];
  const launch: Seed[] = [];
  for (const h of helpers) {
    stdin.push({ path: helperScript(h.slug), text: helperScriptText(h, base) });
    if (h.profile.registryId === profile.registryId) continue; // the same agent: its config is the base's own
    try { launch.push(...h.profile.seed(helperBase(base, h.profile.registryId), undefined, { model: h.model, provider: h.provider })); } catch (e) { notes.push(`${h.profile.name}: ${(e as Error).message}`); }
  }
  if (o.mcp.length && !supportsMcp(profile.spec)) notes.push(`${profile.name} has no MCP support`);
  launch.push(...mcpServerSeeds(profile.spec, o.mcp.map((m) => ({ name: m.name, url: `${base}${m.path}` }))), ...helperAllowSeeds(profile.spec, helpers.map((h) => helperScript(h.slug))));
  return { stdin, launch, notes };
}
